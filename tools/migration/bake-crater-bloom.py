"""Translate the checked-in H5 Gaussian coefficients into SurfaceShader taps."""
from pathlib import Path
import hashlib
import json
import math
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path('D:/Rino_Project/Vox/three/vendor/three/addons/postprocessing/UnrealBloomPass.js')

def main():
    source = SOURCE.read_text(encoding='utf8')
    radii = [int(x) for x in re.search(r'const kernelSizeArray = \[([^]]+)\]', source)[1].split(',')]
    assert radii == [6, 10, 14, 18, 22], 'Source kernels changed; review migration'
    kernels = []
    for level, radius in enumerate(radii, 1):
        sigma = radius / 3
        coefficients = [.39894 * math.exp(-.5 * i * i / sigma**2) / sigma for i in range(radius)]
        taps = []
        for i in range(1, radius, 2):
            a, b = coefficients[i], coefficients[i+1] if i+1 < radius else 0
            taps.append(((i*a+(i+1)*b)/(a+b), a+b))
        lines = ['// Generated by tools/migration/bake-crater-bloom.py; original H5 kernel.',
                 'shader_type spatial;', 'render_mode unshaded, cull_disabled, fog_disabled;',
                 'uniform sampler2D source_map : filter_linear, repeat_disable;',
                 'uniform vec2 direction=vec2(0.0);', 'void fragment() {',
                 f'    vec3 c=texture(source_map,UV).rgb*{coefficients[0]:.12f};']
        for offset, weight in taps:
            lines.append(f'    c+=(texture(source_map,UV+direction*{offset:.12f}).rgb+texture(source_map,UV-direction*{offset:.12f}).rgb)*{weight:.12f};')
        lines.extend(['    ALBEDO=c;', '}', ''])
        (ROOT/f'assets/Shaders/BLGL/CraterPost/Blur{level}.shader').write_text('\n'.join(lines), encoding='utf8')
        kernels.append({'radius': radius, 'center': coefficients[0], 'taps': taps})
    (ROOT/'tools/migration/crater-bloom-reference.json').write_text(json.dumps({
        'source': str(SOURCE), 'sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'kernels': kernels, 'factors': [1, .8, .6, .4, .2], 'composite_multiplier': 3,
        'threshold_smooth_width': .01}, indent=2)+'\n', encoding='utf8')
    print('Generated five H5 Gaussian SurfaceShaders')

if __name__ == '__main__':
    main()
