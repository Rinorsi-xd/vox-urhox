import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
const source=path.resolve(process.argv[2]||'D:/Rino_Project/Vox');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const load=p=>import(pathToFileURL(path.join(source,p)));
const {PART_LIST}=await load('shared/parts/defs.js');
const {applyRot}=await load('shared/core/rotations.js');
const {buildVehicleSpec,buildDebrisShape}=await load('shared/drive/vehicleSpec.js');
const {Blueprint}=await load('shared/build/blueprint.js');
const prefabs=await load('shared/build/prefab.js');
function save(relative,data){const name=path.join(root,relative);fs.mkdirSync(path.dirname(name),{recursive:true});fs.writeFileSync(name+'.tmp',JSON.stringify(data,(k,v)=>v instanceof Set?[...v]:v));fs.renameSync(name+'.tmp',name);}
// Runtime geometry is generated by export-parts.cjs, never by acceptance tests.
const fixtures={cases:[],prefabs:{}};
// Every type, every mounting orientation: tests inverted wheels/tracks, angled hulls,
// rotated thruster force centroids and hover variants without requiring valid assembly.
for(const def of PART_LIST)for(let rot=0;rot<24;rot++){
 const p={id:1,type:def.id,pos:[2,3,-4],rot,_cells:def.cells.map(c=>applyRot(rot,c).map((v,k)=>v+[2,3,-4][k]))};
 const bp={parts:new Map([[1,p]]),connectivity:()=>({coreId:1,reached:new Set([1])})};
 fixtures.cases.push({part:p,spec:buildVehicleSpec(bp),debris:buildDebrisShape([p])});
}
for(const name of ['buildRaceCar','buildTank'])fixtures.prefabs[name]=buildVehicleSpec(prefabs[name](new Blueprint()));
save('tools/migration/source-vehicle-fixtures.json',fixtures);
console.log(JSON.stringify({cases:fixtures.cases.length,prefabs:Object.keys(fixtures.prefabs)}));
