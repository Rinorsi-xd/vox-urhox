import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const baseline=JSON.parse(fs.readFileSync(path.join(root,'docs/migration/outgame-baseline.json')));
const source=path.resolve(process.argv[2]||baseline.snapshot);
const load=p=>import(pathToFileURL(path.join(source,p)));
const {PART_LIST}=await load('shared/parts/defs.js');
const {applyRot}=await load('shared/core/rotations.js');
const {buildVehicleSpec,buildDebrisShape}=await load('shared/drive/vehicleSpec.js');
const {Blueprint}=await load('shared/build/blueprint.js');
const prefabs=await load('shared/build/prefab.js');
function save(relative,data){const name=path.join(root,relative);fs.mkdirSync(path.dirname(name),{recursive:true});fs.writeFileSync(name+'.tmp',JSON.stringify(data,(k,v)=>v instanceof Set?[...v]:ArrayBuffer.isView(v)?Array.from(v):v));fs.renameSync(name+'.tmp',name);}
// Runtime geometry is generated by export-parts.cjs, never by acceptance tests.
const fixtures={commit:baseline.commit,cases:[],prefabs:{},pendingTypes:[],turrets:[]};
// Every type, every mounting orientation: tests inverted wheels/tracks, angled hulls,
// rotated thruster force centroids and hover variants without requiring valid assembly.
for(const def of PART_LIST){
 if(def.mech||def.wing){fixtures.pendingTypes.push(def.id);continue;}
 for(let rot=0;rot<24;rot++){
 const p={id:1,type:def.id,pos:[2,3,-4],rot,_cells:def.cells.map(c=>applyRot(rot,c).map((v,k)=>v+[2,3,-4][k]))};
 const bp=new Blueprint();bp.add(p);bp.connectivity=()=>({coreId:1,reached:new Set([1])});
 fixtures.cases.push({part:p,spec:buildVehicleSpec(bp),debris:buildDebrisShape([p])});
}
}
for(const name of ['buildRaceCar','buildTank'])fixtures.prefabs[name]=buildVehicleSpec(prefabs[name](new Blueprint()));
const {turretRange,turretText}=await load('shared/build/turretRange.js');
const {getTurret}=await load('shared/parts/models.js');
const {WeaponSystem}=await load('shared/combat/weapons.js');
const {ROTATIONS}=await load('shared/core/rotations.js');
for(const type of ['mg3','laser3','sniper5','missile3'])for(const rot of [0,8,16,22])for(const layout of ['clear','low','wall','other-rotor']){
 const bp=new Blueprint();const part=bp.add({type,pos:[0,3,0],rot});
 const owner=new Map([[part.id,1]]);
 if(layout!=='clear')for(let x=-2;x<=2;x++)for(let y=0;y<=(layout==='low'?0:5);y++){
  const local=applyRot(rot,[x,y,2]);const p=bp.add({type:'cube',pos:local.map((v,k)=>v+[0,3,0][k]),rot:22});
  owner.set(p.id,layout==='other-rotor'?2:1);
 }
 const range=turretRange(bp,part,id=>owner.get(id)===1),t=getTurret(type);
 const pivot=applyRot(rot,t.pivot).map((v,k)=>(v+[0,3.5,0][k])*.5);
 const mount={partId:part.id,type,pivot,quat:{...ROTATIONS[rot].quat},range};
 const ws=new WeaponSystem({weapons:[mount]}),w=ws.groups[0].weapons[0],frames=[];
 for(let i=0;i<48;i++){
  const a=(i/47*2-1)*Math.PI;
  const state={pos:[0,0,0],quat:{x:0,y:0,z:0,w:1},aim:[Math.sin(a)*12,i%2?6:-1,Math.cos(a)*12]};
  ws._aim(w,1/30,state);frames.push({state,yaw:w.yaw,pitch:w.pitch,limited:w.limited,err:w.err});
 }
 fixtures.turrets.push({type,rot,layout,parts:[...bp.parts.values()],owner:Object.fromEntries(owner),range,text:turretText(range),frames});
}
save('tools/migration/source-vehicle-fixtures.json',fixtures);
console.log(JSON.stringify({commit:baseline.commit,cases:fixtures.cases.length,prefabs:Object.keys(fixtures.prefabs),pendingTypes:fixtures.pendingTypes,turrets:fixtures.turrets.length}));
