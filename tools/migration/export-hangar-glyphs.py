"""Extract original H5 bay-number outlines; avoids oversized runtime font atlases.

Source font is unchanged. Its OFL accompanies assets/Fonts. Requires fonttools,
numpy and mapbox-earcut in .tmp/font-tooling (build-time dependencies only).
"""
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / '.tmp/font-tooling'))
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
import numpy as np
import mapbox_earcut

font = TTFont('D:/Rino_Project/Vox/shared/fonts/BarlowCondensed-BoldItalic.ttf')
glyphs = font.getGlyphSet()

class Outline(BasePen):
    def __init__(self):
        super().__init__(glyphs)
        self.rings = []
    def _moveTo(self, p):
        self.rings.append([p])
    def _lineTo(self, p):
        self.rings[-1].append(p)
    def _qCurveToOne(self, p1, p2):
        p0 = self._getCurrentPoint()
        def flatten(a,b,c):
            # Quadratic midpoint-to-chord deviation, under .11px at 1080px.
            if max(abs(a[i]-2*b[i]+c[i]) for i in (0,1))/4 <= .1:
                self.rings[-1].append(c)
                return
            ab=tuple((a[i]+b[i])/2 for i in (0,1));bc=tuple((b[i]+c[i])/2 for i in (0,1))
            mid=tuple((ab[i]+bc[i])/2 for i in (0,1))
            flatten(a,ab,mid);flatten(mid,bc,c)
        flatten(p0,p1,p2)
    def _curveToOne(self, p1, p2, p3):
        raise ValueError('Expected original TrueType quadratic outlines')
    def _closePath(self):
        pass

lines = ['-- Generated by tools/migration/export-hangar-glyphs.py; source Barlow OFL.',
         f'return {{units={font["head"].unitsPerEm},glyphs={{']
for char in '0123456789-':
    name = font.getBestCmap()[ord(char)]
    pen = Outline()
    glyphs[name].draw(pen)
    rings = [ring[:-1] if ring[-1] == ring[0] else ring for ring in pen.rings]
    def area(ring):
        return sum(a[0]*b[1]-b[0]*a[1] for a,b in zip(ring, ring[1:]+ring[:1]))/2
    # These eleven glyphs each have one outer contour and zero, one or two holes.
    outer = [ring for ring in rings if area(ring) < 0]
    assert len(outer) == 1
    rings = outer + [ring for ring in rings if area(ring) > 0]
    vertices = np.array([(x,-y) for ring in rings for x,y in ring], dtype=np.float64)
    indices = mapbox_earcut.triangulate_float64(vertices, np.cumsum([len(r) for r in rings], dtype=np.uint32))
    triangles = vertices[indices].reshape((-1, 6))
    expected = abs(sum(area(ring) for ring in rings))
    actual = sum(abs((t[2]-t[0])*(t[5]-t[1])-(t[4]-t[0])*(t[3]-t[1]))/2 for t in triangles)
    assert abs(actual-expected) < .001, (char, actual, expected)
    lines.append(f"['{char}']={{advance={font['hmtx'][name][0]},triangles={{")
    for start in range(0,len(triangles),8):
        lines.append(''.join('{' + ','.join(f'{v:.4f}' for v in t) + '},' for t in triangles[start:start+8]))
    lines.append('}},')
lines.append('}}')
(root / 'scripts/render/HangarGlyphData.lua').write_text('\n'.join(lines) + '\n', encoding='utf8')
