local Views=require 'render.WindowViewports'
V.atFrame(55,function()
    local nativeGraphics=graphics
    local function Size(w,h,fn)
        graphics={GetWidth=function() return w end,GetHeight=function() return h end}
        local ok,message=pcall(fn);graphics=nativeGraphics
        if not ok then error(message) end
    end
    local original=Views.Get(0);local count=renderer.numViewports
    local scene=Scene();scene:CreateComponent('Octree')
    local cam=scene:CreateChild('WindowGuardTest'):CreateComponent('Camera')
    local first,second=Viewport:new(scene,cam),Viewport:new(scene,cam)
    local extra=count;renderer:SetNumViewports(count+1)
    Views.Set(extra,first)
    V.assert(renderer:GetViewport(extra)==first,'secondary screen viewport initially active')
    Size(0,0,function()
        Views.Refresh()
        V.assert(renderer:GetViewport(0)==nil and renderer:GetViewport(extra)==nil,'zero-area suspends primary and secondary views')
        V.assert(Views.Get(0)==original and Views.Get(extra)==first,'owners retain viewport intent while suspended')
        Views.Set(extra,second)
        V.assert(renderer:GetViewport(extra)==nil and Views.Get(extra)==second,'hidden replacement does not draw or restore old viewport')
        Views.Set(0,nil)
    end)
    Views.Refresh()
    V.assert(renderer:GetViewport(0)==nil,'opaque page remains hidden after window restoration')
    V.assert(renderer:GetViewport(extra)==second,'latest secondary viewport restored')
    Views.Set(0,original)
    Size(0,1080,function()
        Views.Refresh();Views.Set(extra,nil)
        V.assert(renderer:GetViewport(0)==nil,'zero width alone suspends screen')
    end)
    Views.Refresh()
    V.assert(renderer:GetViewport(extra)==nil,'disposed hidden secondary view is not resurrected')
    V.assert(renderer:GetViewport(0)==original,'primary restored with original scene and camera')
    Size(1920,0,function()
        Views.Set(extra,first);Views.Refresh()
        V.assert(renderer:GetViewport(extra)==nil,'new viewport at zero height remains suspended')
    end)
    Size(1,1,function()
        Views.Refresh()
        V.assert(renderer:GetViewport(0)==original and renderer:GetViewport(extra)==first,'positive one-pixel screen restores requested views')
    end)
    renderer:SetNumViewports(count);Views.Refresh()
    V.assert(Views.Get(extra)==nil,'shrinking viewport array drops retired slot')
    renderer:SetNumViewports(count+1);Views.Refresh()
    V.assert(renderer:GetViewport(extra)==nil,'reusing slot cannot revive previous scene')
    Views.Set(extra,first)
    Size(0,0,function() Views.Refresh();Views.Stop() end)
    Views.Start();Views.Refresh()
    V.assert(renderer:GetViewport(extra)==nil and renderer:GetViewport(0)==nil,'shutdown while hidden releases intent')
    Views.Set(0,original);renderer:SetNumViewports(count);scene:Dispose()
    V.assert(renderer:GetViewport(0)==original,'test restores real hall viewport')
    V.finish()
end)
