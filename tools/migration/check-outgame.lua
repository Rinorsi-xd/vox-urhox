V.atFrame(495,function()
    local s=Hud.GetState();Shot('market')
    local lobby=s.app.salvageLobby;local savedItems=lobby.data.items;local old=lobby.data.credits
    local rules=require('core.ResourceData').Read('UI/SalvageRules.json')
    V.assert(rules.cells==120 and rules.stack['part:cube']==99 and rules.stack['part:drive1']==10 and rules.stack.scrap==50 and rules.stack.ration==10 and rules.stack.repair==5,'Frozen warehouse capacity and stack limits')
    local rejected,reason=lobby:Trade('scrap',1,false)
    V.assert(not rejected and reason=='仓库放不下了','Source filled warehouse rejects over-capacity purchase')
    V.assert(lobby.data.credits==old and lobby.data.items==savedItems,'Rejected trade preserves wallet and items')
    lobby.data.items={scrap=36};local before=lobby:Owned('scrap')
    local ok=lobby:Trade('scrap',2,false);V.assert(ok,'Trader buys goods')
    V.assert(lobby.data.credits==old-24 and lobby:Owned('scrap')==before+2,'Buy changes credits and inventory together')
    ok=lobby:Trade('scrap',2,true);V.assert(ok,'Trader sells loose goods')
    V.assert(lobby.data.credits==old-10 and lobby:Owned('scrap')==before,'Sell uses source 60 percent price')
    lobby.data.items=savedItems;lobby.data.credits=old;lobby:Save()
    s.SetLobby('arena')
end)
