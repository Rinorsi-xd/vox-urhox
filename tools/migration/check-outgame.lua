V.atFrame(85,function()
    V.assert(renderer:GetViewport(0)==nil,'Opaque source workshop suspends hidden hall rendering')
    local paragraph=Hud.GetState().page.description
    local layout=paragraph.layout
    V.assert(#layout.lines==3,'Source feature description clamps to three lines')
    local line=layout.lines[3];local last=line.runs[#line.runs]
    V.assert(last.text:sub(-3)==utf8.char(0x2026) and line.width<=460,'Source clamp ends in a fitting ellipsis')
    local measurements=paragraph.measurements
    paragraph:Measure(paragraph.context,paragraph.content,460,{219,238,255,191})
    V.assert(paragraph.measurements==measurements,'Equal color values reuse the measured paragraph')
    Shot('workshop')
    local s=Hud.GetState();local ws=s.workshop;local carousel=require 'ui.WorkshopCarousel'
    local delayed={workshop={selected='scorpion',elapsed=3}}
    carousel.Ensure(delayed.workshop)
    local shelfAlpha,shelfOffset=carousel.Shelf(delayed.workshop,1)
    V.assert(shelfAlpha==0 and shelfOffset==20,'Original shelf waits 120ms below its destination')
    local alpha,offset=carousel.Caption(delayed.workshop,1)
    V.assert(alpha==0 and offset==-30,'Feature entry starts 30px left with original hidden opacity')
    carousel.Step(delayed,.08)
    shelfAlpha,shelfOffset=carousel.Shelf(delayed.workshop,9)
    V.assert(shelfAlpha==0 and shelfOffset==20,'Last shelf card waits original 360ms stagger')
    alpha,offset=carousel.Caption(delayed.workshop,6)
    V.assert(alpha==0 and offset==-30,'Sixth caption sibling waits its original 200ms delay')
    local backend={requests={},cancelled={}}
    function backend:Exists() return false end
    function backend:DownloadResources(paths,done)
        self.requests[#self.requests+1]={path=paths[1],done=done};return #self.requests
    end
    function backend:CancelDownloadGroup(group) self.cancelled[group]=true end
    delayed.workshop.imageGate=require('app.ResourceGate').New(backend)
    carousel.Select(delayed,'fox');carousel.Step(delayed,.3)
    shelfAlpha,shelfOffset=carousel.Shelf(delayed.workshop,9)
    V.assert(shelfAlpha>0 and shelfAlpha<1 and shelfOffset>0,'Last shelf card enters after original delay')
    V.assert(delayed.workshop.caption.distance==30,'Pending download does not restart the outgoing caption')
    V.assert(delayed.workshop.selected=='scorpion' and delayed.workshop.pending=='fox','Cold download preserves matching caption and outgoing picture')
    V.assert(delayed.workshop.slides.scorpion.alpha.value==1 and delayed.workshop.slides.fox.alpha.value==0,'Crossfade waits for original image download')
    carousel.Select(delayed,'trooper');backend.requests[1].done(true,0)
    V.assert(backend.cancelled[1] and delayed.workshop.selected=='scorpion','Rapid selection cancels old image observer and ignores its late callback')
    backend.requests[2].done(true,0);carousel.Step(delayed,.3)
    V.assert(delayed.workshop.selected=='trooper' and delayed.workshop.slides.trooper.alpha.value>0,'Ready image commits selection and starts source transition')
    alpha,offset=carousel.Caption(delayed.workshop,6)
    V.assert(delayed.workshop.caption.distance==24 and alpha>0 and alpha<1 and offset<0,'Ready recommendation restarts original 24px staggered caption entry')
    carousel.Step(delayed,.17);alpha,offset=carousel.Caption(delayed.workshop,6)
    shelfAlpha,shelfOffset=carousel.Shelf(delayed.workshop,9)
    V.assert(shelfAlpha==1 and shelfOffset==0,'Shelf settles exactly without restarting on recommendation change')
    V.assert(alpha==1 and offset==0,'Caption settles after original 260ms duration plus 200ms stagger')
    carousel.Select(delayed,'fox');carousel.Leave(delayed.workshop);backend.requests[3].done(true,0)
    V.assert(delayed.workshop.slides==nil and delayed.workshop.pending==nil and delayed.workshop.shelf==nil,'Leaving ignores a pending image completion and releases shelf state')
    carousel.Select(s,'hawk');carousel.Step(s,.3)
    local outgoing=ws.slides.scorpion.alpha.value;local incoming=ws.slides.hawk.alpha.value
    V.assert(outgoing>0 and outgoing<1 and incoming>0 and incoming<1,'Changing recommendation crossfades both source slides')
    local keep={};carousel.Keep(ws,keep)
    V.assert(keep['UI/Prefabs/scorpion.jpg'] and keep['UI/Prefabs/hawk.jpg'],'Outgoing image survives page rebuild during fade')
    carousel.Select(s,'raceCar')
    V.assert(ws.slides.scorpion.alpha.value==outgoing and ws.slides.hawk.alpha.value==incoming,'Interrupting a fade preserves its current opacity')
    carousel.Step(s,1)
    V.assert(ws.slides.scorpion.alpha.value==0 and ws.slides.hawk.alpha.value==0 and ws.slides.raceCar.alpha.value==1,'Interrupted fade settles to a single recommendation')
    carousel.Select(s,'scorpion');carousel.Step(s,1)
    s.WorkshopOpen('scorpion')
end)
